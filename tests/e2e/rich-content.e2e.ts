test('previews sanitized SVG, PDF pages and audio without executing SVG or loading its resources', async ({ page }, info) => {
  const blocked: string[] = []
  page.on('request', request => { if (request.url().includes('blocked.example')) blocked.push(request.url()) })
  await expect(page.getByRole('img', { name: 'SVG 图片', exact: true })).toBeVisible()
  await expect.poll(() => page.getByRole('img', { name: 'SVG 图片', exact: true }).evaluate((img: HTMLImageElement) => img.naturalWidth)).toBe(320)
  const src = await page.getByRole('img', { name: 'SVG 图片', exact: true }).getAttribute('src')
  const svg = decodeURIComponent(src!.slice(src!.indexOf(',') + 1))
  expect(svg).not.toContain('<script'); expect(svg).not.toContain('onload'); expect(svg).not.toContain('blocked.example')
  expect(await page.evaluate(() => (window as any).__svgXss)).toBeUndefined()
  await page.getByRole('button', { name: 'SVG 文件', exact: true }).click()
  const panel = page.getByRole('complementary', { name: '文件预览', exact: true })
  await expect(panel.getByRole('img', { name: 'result.svg', exact: true })).toBeVisible()
  await panel.getByRole('button', { name: '关闭文件预览', exact: true }).click()
  await page.getByRole('button', { name: 'PDF 文件', exact: true }).click()
  const canvas = panel.locator('canvas')
  await expect(canvas).toBeVisible()
  await expect(panel.getByText('1 / 2', { exact: true })).toBeVisible()
  await expect.poll(() => canvas.evaluate((canvas: HTMLCanvasElement) => Array.from(canvas.getContext('2d')!.getImageData(Math.floor(canvas.width * .4), Math.floor(canvas.height * .6), 1, 1).data))).toEqual([255, 0, 0, 255])
  const first = await canvas.evaluate((canvas: HTMLCanvasElement) => canvas.toDataURL())
  await panel.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(panel.getByText('2 / 2', { exact: true })).toBeVisible()
  await expect.poll(() => canvas.evaluate((canvas: HTMLCanvasElement) => canvas.toDataURL())).not.toBe(first)
  await expect.poll(() => canvas.evaluate((canvas: HTMLCanvasElement) => Array.from(canvas.getContext('2d')!.getImageData(Math.floor(canvas.width * .4), Math.floor(canvas.height * .6), 1, 1).data))).toEqual([0, 0, 255, 255])
  await panel.screenshot({ path: info.outputPath('pdf-preview.png') })
  await panel.getByRole('button', { name: '关闭文件预览', exact: true }).click()
  await page.getByRole('button', { name: '音频文件', exact: true }).click()
  await expect.poll(() => panel.locator('audio').evaluate((audio: HTMLAudioElement) => audio.duration)).toBeGreaterThan(0)
  expect(blocked).toEqual([])
})

