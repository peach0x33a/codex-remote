test('keeps MCP forms pending until an explicit, validated answer and preserves typed values', async ({ page, request }, info) => {
  await request.get(MOCK_URL + '/test/elicitation')
  const form = page.locator('.elicitation-form')
  await expect(form.getByText('请填写发布信息', { exact: true })).toBeVisible()
  const responses = async () => (await (await request.get(MOCK_URL + '/test/metrics')).json()).requests.filter((entry: any) => entry.method === 'elicitation/response')
  expect(await responses()).toEqual([])
  await form.getByRole('button', { name: '提交', exact: true }).click()
  await expect(form.getByRole('alert')).toContainText('标题')
  await form.getByLabel('标题', { exact: false }).fill('发布说明')
  await form.getByLabel('数量', { exact: false }).fill('2')
  await form.getByLabel('公开发布', { exact: false }).selectOption('false')
  await form.getByLabel('标签', { exact: false }).selectOption(['a', 'b'])
  await form.screenshot({ path: info.outputPath('mcp-form.png') })
  await form.getByRole('button', { name: '提交', exact: true }).click()
  await expect(form).toHaveCount(0)
  expect((await responses())[0].params.result).toEqual({ action: 'accept', content: { title: '发布说明', count: 2, confirm: false, labels: ['a', 'b'] }, _meta: null })
})

test('MCP URL requests open only on user action and support explicit cancellation', async ({ page, request }) => {
  await request.get(MOCK_URL + '/test/elicitation?mode=url')
  const form = page.locator('.elicitation-form')
  await expect(form.getByRole('link')).toHaveAttribute('href', 'https://auth.example/authorize')
  expect(page.context().pages()).toHaveLength(1)
  await page.route('https://auth.example/**', route => route.fulfill({ body: '授权完成', contentType: 'text/html' }))
  const opened = page.waitForEvent('popup')
  await form.getByRole('link').click()
  const popup = await opened; await popup.close()
  await form.getByRole('button', { name: '取消', exact: true }).click()
  await expect(form).toHaveCount(0)
  const metrics = await (await request.get(MOCK_URL + '/test/metrics')).json()
  expect(metrics.requests.find((entry: any) => entry.method === 'elicitation/response').params.result).toEqual({ action: 'cancel', content: null, _meta: null })
})
