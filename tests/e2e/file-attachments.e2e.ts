test('upload rejection and cancellation preserve the message and never submit an incomplete file', async ({ page, request }) => {
  const composer = page.getByRole('textbox', { name: '发送给 Codex 的消息' }), input = page.getByLabel('选择附件', { exact: true })
  await composer.fill('不要丢失这份草稿')
  await request.get(MOCK_URL + '/test/scenario?name=file-upload-error')
  await input.setInputFiles({ name: '上传失败.docx', mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer: Buffer.from('data') })
  await expect(page.getByRole('alert')).toContainText('测试文件上传失败')
  await expect(composer).toHaveText('不要丢失这份草稿')
  await expect(composer.locator('.editor-file-chip')).toHaveCount(0)
  await request.get(MOCK_URL + '/test/scenario?name=file-upload-slow')
  await input.setInputFiles({ name: '取消上传.bin', mimeType: 'application/octet-stream', buffer: Buffer.alloc(524289, 1) })
  await page.getByRole('button', { name: '取消添加附件', exact: true }).click()
  await expect(page.getByRole('button', { name: '取消添加附件', exact: true })).toHaveCount(0)
  await expect(composer).toHaveText('不要丢失这份草稿')
  await expect(composer.locator('.editor-file-chip')).toHaveCount(0)
  const metrics = await (await request.get(MOCK_URL + '/test/metrics')).json()
  expect(metrics.requests.some((entry: { method: string }) => entry.method === 'turn/start')).toBe(false)
  expect(metrics.requests.some((entry: { method: string; params: { command?: string[] } }) => entry.method === 'command/exec' && entry.params.command?.[5] === 'finish')).toBe(false)
})
