  await page.getByLabel('选择附件', { exact: true }).setInputFiles({ name: '队列.docx', mimeType: 'application/octet-stream', buffer: Buffer.from('doc content') })
  await expect(composer.locator('.editor-file-chip')).toHaveCount(1)
  await composer.press('Tab')
  const queue = page.getByRole('region', { name: '消息队列', exact: true })
